  let currentLang = 'fr';

  function getStoredLang() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'en' || stored === 'fr') return stored;
    } catch (e) {}
    if (typeof navigator !== 'undefined' && navigator.language && navigator.language.startsWith('en')) {
      return 'en';
    }
    return 'fr';
  }

  function setLang(lang) {
    if (lang !== 'fr' && lang !== 'en') lang = 'fr';
    currentLang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}

    if (typeof document !== 'undefined') {
      if (document.documentElement) document.documentElement.lang = lang;

      // Update Toggle Buttons
      const btnFr = document.getElementById('langFr');
      const btnEn = document.getElementById('langEn');
      if (btnFr) btnFr.classList.toggle('active', lang === 'fr');
      if (btnEn) btnEn.classList.toggle('active', lang === 'en');

      // Apply translations to static DOM elements
      applyTranslations();
    }

    // Dispatch event so dynamic JS views can refresh
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function' && typeof CustomEvent === 'function') {
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
  }

  function t(key, fallback = '') {
    const langDict = DICTIONARY[currentLang] || DICTIONARY.fr;
    if (langDict[key] !== undefined) return langDict[key];
    const frDict = DICTIONARY.fr;
    if (frDict[key] !== undefined) return frDict[key];
    return fallback || key;
  }

  function applyTranslations() {
    // 1. Text elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (val) el.innerHTML = val;
    });

    // 2. Title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = t(key);
      if (val) el.setAttribute('title', val);
    });

    // 3. Placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = t(key);
      if (val) el.setAttribute('placeholder', val);
    });
  }

  function init() {
    currentLang = getStoredLang();
    document.documentElement.lang = currentLang;

    // Attach click listeners to language buttons
    const btnFr = document.getElementById('langFr');
    const btnEn = document.getElementById('langEn');
    if (btnFr) btnFr.addEventListener('click', () => setLang('fr'));
    if (btnEn) btnEn.addEventListener('click', () => setLang('en'));

    // Initial translation pass once DOM is ready
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', () => {
        setLang(currentLang);
      });
    } else {
      setLang(currentLang);
    }
  }

